fn wrap_pdf_text(text: &str, width: f32, font_size: f32, max_lines: usize) -> Vec<String> {
    let normalized = single_line_text(text);
    if normalized.is_empty() {
        return vec![String::new()];
    }
    if !can_encode_win_ansi(&normalized) {
        return wrap_unicode_pdf_text(&normalized, width, font_size, max_lines);
    }

    let max_chars = (width / (font_size * 0.53)).floor().max(1.0) as usize;

    let mut lines = Vec::<String>::new();
    let mut current = String::new();
    for word in normalized.split_whitespace() {
        let candidate_len =
            current.chars().count() + usize::from(!current.is_empty()) + word.chars().count();
        if candidate_len <= max_chars {
            if !current.is_empty() {
                current.push(' ');
            }
            current.push_str(word);
            continue;
        }
        if !current.is_empty() {
            lines.push(std::mem::take(&mut current));
        }
        let mut chunk = String::new();
        for character in word.chars() {
            chunk.push(character);
            if chunk.chars().count() == max_chars {
                lines.push(std::mem::take(&mut chunk));
            }
        }
        current = chunk;
    }
    if !current.is_empty() {
        lines.push(current);
    }
    if lines.len() > max_lines.max(1) {
        lines.truncate(max_lines.max(1));
        let last = lines.last_mut().expect("at least one PDF line");
        while last.chars().count() + 3 > max_chars && !last.is_empty() {
            last.pop();
        }
        last.push_str("...");
    }
    lines
}

fn wrap_unicode_pdf_text(text: &str, width: f32, font_size: f32, max_lines: usize) -> Vec<String> {
    let max_lines = max_lines.max(1);
    let mut lines = Vec::<String>::new();
    let mut current = String::new();

    for word in text.split_whitespace() {
        let candidate = if current.is_empty() {
            word.to_string()
        } else {
            format!("{current} {word}")
        };
        if pdf_text_width(&candidate, font_size) <= width {
            current = candidate;
            continue;
        }

        if !current.is_empty() {
            lines.push(std::mem::take(&mut current));
        }
        if pdf_text_width(word, font_size) <= width {
            current.push_str(word);
            continue;
        }

        for cluster in unicode_scalar_clusters(word) {
            let candidate = format!("{current}{cluster}");
            if !current.is_empty() && pdf_text_width(&candidate, font_size) > width {
                lines.push(std::mem::take(&mut current));
            }
            current.push_str(&cluster);
        }
    }
    if !current.is_empty() {
        lines.push(current);
    }
    if lines.is_empty() {
        lines.push(String::new());
    }

    if lines.len() > max_lines {
        lines.truncate(max_lines);
        let last = lines.last_mut().expect("at least one PDF line");
        while !last.is_empty() && pdf_text_width(&format!("{last}..."), font_size) > width {
            last.pop();
        }
        last.push_str("...");
    }
    lines
}

fn unicode_scalar_clusters(text: &str) -> Vec<String> {
    let mut clusters = Vec::<String>::new();
    for character in text.chars() {
        if is_unicode_combining_mark(character)
            || character == '\u{fe0f}'
            || character == '\u{200d}'
        {
            if let Some(last) = clusters.last_mut() {
                last.push(character);
                continue;
            }
        }
        clusters.push(character.to_string());
    }
    clusters
}

fn is_unicode_combining_mark(character: char) -> bool {
    matches!(
        character as u32,
        0x0300..=0x036f
            | 0x0483..=0x0489
            | 0x0591..=0x05bd
            | 0x05bf
            | 0x05c1..=0x05c2
            | 0x05c4..=0x05c5
            | 0x0610..=0x061a
            | 0x064b..=0x065f
            | 0x0670
            | 0x06d6..=0x06ed
            | 0x1ab0..=0x1aff
            | 0x1dc0..=0x1dff
            | 0x20d0..=0x20ff
            | 0xfe20..=0xfe2f
    )
}

fn pdf_text_width(text: &str, font_size: f32) -> f32 {
    crate::vector_text::measure_project_text_width_standalone(text, font_size)
        .unwrap_or_else(|| text.chars().count() as f32 * font_size)
}

fn add_pdf_footers(pages: &mut [PdfCanvas]) {
    let total = pages.len();
    for (index, page) in pages.iter_mut().enumerate() {
        page.text(PDF_MARGIN, 18.0, 7.0, false, "Generated by Coquerythmo");
        page.text(
            PDF_WIDTH - 72.0,
            18.0,
            7.0,
            false,
            &format!("Page {} / {total}", index + 1),
        );
    }
}

fn build_pdf(pages: &[PdfCanvas]) -> Vec<u8> {
    struct PageObjects {
        page: usize,
        content: usize,
        images: Vec<usize>,
    }

    let mut next_object = 5_usize;
    let page_objects: Vec<_> = pages
        .iter()
        .map(|page| {
            let page_object = next_object;
            let content_object = next_object + 1;
            next_object += 2;
            let images = (0..page.image_masks.len())
                .map(|_| {
                    let image_object = next_object;
                    next_object += 1;
                    image_object
                })
                .collect();
            PageObjects {
                page: page_object,
                content: content_object,
                images,
            }
        })
        .collect();

    let mut objects = Vec::<Vec<u8>>::new();
    objects.push(b"<< /Type /Catalog /Pages 2 0 R >>".to_vec());

    let kids = page_objects
        .iter()
        .map(|objects| format!("{} 0 R", objects.page))
        .collect::<Vec<_>>()
        .join(" ");
    objects.push(format!("<< /Type /Pages /Kids [{kids}] /Count {} >>", pages.len()).into_bytes());
    objects.push(
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>"
            .to_vec(),
    );
    objects.push(
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>"
            .to_vec(),
    );

    for (page, page_objects) in pages.iter().zip(&page_objects) {
        debug_assert_eq!(objects.len() + 1, page_objects.page);
        let xobjects = if page_objects.images.is_empty() {
            String::new()
        } else {
            format!(
                " /XObject << {} >>",
                page_objects
                    .images
                    .iter()
                    .enumerate()
                    .map(|(index, object)| format!("/Im{} {object} 0 R", index + 1))
                    .collect::<Vec<_>>()
                    .join(" ")
            )
        };
        objects.push(
            format!(
                "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {PDF_WIDTH:.0} {PDF_HEIGHT:.0}] /Resources << /Font << /F1 3 0 R /F2 4 0 R >>{xobjects} >> /Contents {} 0 R >>",
                page_objects.content
            )
            .into_bytes(),
        );
        let content = page.content.as_bytes();
        let mut stream = format!("<< /Length {} >>\nstream\n", content.len()).into_bytes();
        stream.extend_from_slice(content);
        stream.extend_from_slice(b"endstream");
        objects.push(stream);

        for (image, image_object) in page.image_masks.iter().zip(&page_objects.images) {
            debug_assert_eq!(objects.len() + 1, *image_object);
            let mut stream = format!(
                "<< /Type /XObject /Subtype /Image /Width {} /Height {} /ImageMask true /BitsPerComponent 1 /Decode [1 0] /Interpolate true /Length {} >>\nstream\n",
                image.width,
                image.height,
                image.packed_bits.len()
            )
            .into_bytes();
            stream.extend_from_slice(&image.packed_bits);
            stream.extend_from_slice(b"\nendstream");
            objects.push(stream);
        }
    }

    let mut pdf = b"%PDF-1.4\n%\xE2\xE3\xCF\xD3\n".to_vec();
    let mut offsets = vec![0_usize];
    for (index, object) in objects.iter().enumerate() {
        offsets.push(pdf.len());
        pdf.extend_from_slice(format!("{} 0 obj\n", index + 1).as_bytes());
        pdf.extend_from_slice(object);
        pdf.extend_from_slice(b"\nendobj\n");
    }
    let xref_offset = pdf.len();
    pdf.extend_from_slice(format!("xref\n0 {}\n", objects.len() + 1).as_bytes());
    pdf.extend_from_slice(b"0000000000 65535 f \n");
    for offset in offsets.into_iter().skip(1) {
        pdf.extend_from_slice(format!("{offset:010} 00000 n \n").as_bytes());
    }
    pdf.extend_from_slice(
        format!(
            "trailer\n<< /Size {} /Root 1 0 R >>\nstartxref\n{xref_offset}\n%%EOF\n",
            objects.len() + 1
        )
        .as_bytes(),
    );
    pdf
}

fn pdf_string(text: &str) -> String {
    let mut escaped = String::new();
    for byte in text
        .chars()
        .map(|character| win_ansi_byte(character).unwrap_or(b'?'))
    {
        match byte {
            b'(' => escaped.push_str("\\("),
            b')' => escaped.push_str("\\)"),
            b'\\' => escaped.push_str("\\\\"),
            0x20..=0x7e => escaped.push(byte as char),
            _ => write!(escaped, "\\{byte:03o}").expect("String writes cannot fail"),
        }
    }
    escaped
}

fn can_encode_win_ansi(text: &str) -> bool {
    text.chars()
        .all(|character| win_ansi_byte(character).is_some())
}

fn win_ansi_byte(character: char) -> Option<u8> {
    Some(match character {
        '\u{0000}'..='\u{001f}' => b' ',
        '\u{0020}'..='\u{007e}' => character as u8,
        '\u{00a0}'..='\u{00ff}' => character as u8,
        '\u{20ac}' => 0x80,
        '\u{201a}' => 0x82,
        '\u{0192}' => 0x83,
        '\u{201e}' => 0x84,
        '\u{2026}' => 0x85,
        '\u{2020}' => 0x86,
        '\u{2021}' => 0x87,
        '\u{02c6}' => 0x88,
        '\u{2030}' => 0x89,
        '\u{0160}' => 0x8a,
        '\u{2039}' => 0x8b,
        '\u{0152}' => 0x8c,
        '\u{017d}' => 0x8e,
        '\u{2018}' => 0x91,
        '\u{2019}' => 0x92,
        '\u{201c}' => 0x93,
        '\u{201d}' => 0x94,
        '\u{2022}' => 0x95,
        '\u{2013}' => 0x96,
        '\u{2014}' => 0x97,
        '\u{02dc}' => 0x98,
        '\u{2122}' => 0x99,
        '\u{0161}' => 0x9a,
        '\u{203a}' => 0x9b,
        '\u{0153}' => 0x9c,
        '\u{017e}' => 0x9e,
        '\u{0178}' => 0x9f,
        _ => return None,
    })
}

fn pdf_utf16_hex(text: &str) -> String {
    let mut encoded = String::from("FEFF");
    for unit in text.encode_utf16() {
        write!(encoded, "{unit:04X}").expect("String writes cannot fail");
    }
    encoded
}

fn write_bytes(output: &Path, bytes: &[u8]) -> Result<(), String> {
    std::fs::write(output, bytes)
        .map_err(|error| format!("Cannot write {}: {error}", output.display()))
}

