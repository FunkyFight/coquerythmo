/// Export several mono or multichannel inputs as separate Broadcast Wave
/// stems. This is intentionally a batch of files rather than a proprietary
/// container, which keeps each stem independently usable by a DAW.
pub fn export_bwf_stems(
    project: &Project,
    fps: f64,
    stems: &[AudioStemExport<'_>],
    cancel: &AtomicBool,
) -> Result<(), String> {
    for stem in stems {
        let options = AudioExportOptions {
            format: AudioDeliveryFormat::Bwf,
            track: stem.track,
            language_name: stem.language_name,
            stem_name: stem.stem_name,
            duration_frames: stem.duration_frames,
        };
        export_audio(project, fps, stem.input, stem.output, &options, cancel)?;
    }
    Ok(())
}

/// Last meaningful project frame, suitable as an explicit audio delivery
/// duration when a caller wants all stems to have equal length.
pub fn project_delivery_duration_frames(project: &Project) -> i64 {
    project
        .lines()
        .map(RythmoLine::end_frame)
        .chain(project.markers().iter().map(|marker| marker.frame))
        .max()
        .unwrap_or(1)
        .max(1)
}

fn audio_delivery_filter(offset_frames: i64, fps: f64, duration_frames: Option<i64>) -> String {
    let offset_seconds = offset_frames as f64 / fps;
    let mut filters = Vec::<String>::new();
    if offset_frames > 0 {
        let delay_ms = (offset_seconds * 1000.0).round().max(0.0) as i64;
        filters.push(format!("adelay={delay_ms}:all=1"));
    } else if offset_frames < 0 {
        filters.push(format!("atrim=start={}", format_decimal(-offset_seconds)));
    }
    if let Some(duration_frames) = duration_frames {
        let duration = format_decimal(duration_frames as f64 / fps);
        filters.push(format!("apad=whole_dur={duration}"));
        filters.push(format!("atrim=duration={duration}"));
    }
    filters.push("asetpts=PTS-STARTPTS".to_string());
    filters.join(",")
}

fn format_decimal(value: f64) -> String {
    let mut value = format!("{value:.9}");
    while value.ends_with('0') {
        value.pop();
    }
    if value.ends_with('.') {
        value.push('0');
    }
    value
}

fn temporary_audio_path(output: &Path, format: AudioDeliveryFormat) -> std::path::PathBuf {
    let parent = output.parent().unwrap_or_else(|| Path::new("."));
    let filename = output
        .file_name()
        .and_then(|name| name.to_str())
        .filter(|name| !name.is_empty())
        .unwrap_or("audio");
    let stamp = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|duration| duration.as_nanos())
        .unwrap_or(0);
    parent.join(format!(
        ".{filename}.{}.{}.part.{}",
        std::process::id(),
        stamp,
        format.extension()
    ))
}

fn replace_output(temporary: &Path, output: &Path) -> Result<(), String> {
    if output.exists() {
        std::fs::remove_file(output)
            .map_err(|error| format!("Cannot replace {}: {error}", output.display()))?;
    }
    if let Err(error) = std::fs::rename(temporary, output) {
        let _ = std::fs::remove_file(temporary);
        return Err(format!(
            "Cannot finalize audio delivery {}: {error}",
            output.display()
        ));
    }
    Ok(())
}

