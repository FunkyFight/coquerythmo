/// Error returned when an FFmpeg delivery was cancelled by its caller.
pub const DELIVERY_EXPORT_CANCELLED_MESSAGE: &str = "Export canceled";

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum SubtitleFormat {
    Json,
    Srt,
    Ass,
    Detx,
}

impl SubtitleFormat {
    pub fn extension(self) -> &'static str {
        match self {
            Self::Json => "json",
            Self::Srt => "srt",
            Self::Ass => "ass",
            Self::Detx => "detx",
        }
    }
}

/// Export one active bande rythmo to any supported subtitle/interchange format.
pub fn export_subtitle(
    project: &Project,
    fps: f64,
    output: &Path,
    language_name: &str,
    format: SubtitleFormat,
) -> Result<(), String> {
    match format {
        SubtitleFormat::Json => export_json(project, fps, output),
        SubtitleFormat::Srt => export_srt(project, fps, output),
        SubtitleFormat::Ass => export_ass(project, fps, output, language_name),
        SubtitleFormat::Detx => export_detx(project, fps, output, language_name),
    }
}

/// Build the legacy-compatible JSON representation through [`ProjectData`].
pub fn json_document(project: &Project, fps: f64) -> Result<String, String> {
    validate_fps(fps)?;
    let mut data = ProjectData::from_project(project, fps);
    // A delivery JSON represents the selected bande only. The project archive
    // remains the place where the complete multilingual project is stored.
    data.languages.clear();
    data.active_language_id = None;
    serde_json::to_string_pretty(&data).map_err(|error| format!("JSON serialize error: {error}"))
}

pub fn export_json(project: &Project, fps: f64, output: &Path) -> Result<(), String> {
    write_text(output, &json_document(project, fps)?)
}

/// Build a UTF-8 SubRip document. Lines are sorted chronologically and invalid
/// or empty lines are omitted.
pub fn srt_document(project: &Project, fps: f64) -> Result<String, String> {
    validate_fps(fps)?;
    let mut document = String::new();
    for (index, line) in delivery_lines(project).into_iter().enumerate() {
        let (start_ms, end_ms) = subtitle_milliseconds(line, fps);
        writeln!(document, "{}", index + 1).expect("String writes cannot fail");
        writeln!(
            document,
            "{} --> {}",
            srt_timestamp(start_ms),
            srt_timestamp(end_ms)
        )
        .expect("String writes cannot fail");
        document.push_str(&normalized_text(&line.text));
        document.push_str("\n\n");
    }
    Ok(document.replace('\n', "\r\n"))
}

pub fn export_srt(project: &Project, fps: f64, output: &Path) -> Result<(), String> {
    write_text(output, &srt_document(project, fps)?)
}

/// Build an Advanced SubStation Alpha document. A style is emitted per role so
/// character colours survive the export; the ASS `Name` field also carries the
/// role name.
pub fn ass_document(project: &Project, fps: f64, language_name: &str) -> Result<String, String> {
    validate_fps(fps)?;
    let lines = delivery_lines(project);
    let mut roles = BTreeMap::<String, ([f32; 4], String)>::new();
    for line in &lines {
        let next_index = roles.len() + 1;
        roles
            .entry(line.character_name.clone())
            .or_insert_with(|| (line.character_color, format!("Role{next_index}")));
    }

    let title = if language_name.trim().is_empty() {
        "Coquerythmo".to_string()
    } else {
        format!("Coquerythmo - {}", language_name.trim())
    };
    let mut document = format!(
        "[Script Info]\n; Generated by Coquerythmo\nTitle: {}\nScriptType: v4.00+\nWrapStyle: 0\nScaledBorderAndShadow: yes\nPlayResX: 1920\nPlayResY: 1080\nYCbCr Matrix: TV.709\n\n[V4+ Styles]\nFormat: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding\nStyle: Default,Arial,54,&H00FFFFFF,&H0000FFFF,&H00101010,&H80000000,0,0,0,0,100,100,0,0,1,2,0,2,70,70,48,1\n",
        ass_header_field(&title)
    );
    for (name, (color, style)) in &roles {
        writeln!(
            document,
            "Style: {},Arial,54,{},{},&H00101010,&H80000000,0,0,0,0,100,100,0,0,1,2,0,2,70,70,48,1",
            style,
            ass_color(*color),
            ass_color([1.0, 1.0, 0.0, color[3]])
        )
        .expect("String writes cannot fail");
        let _ = name;
    }
    document.push_str(
        "\n[Events]\nFormat: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n",
    );
    for line in lines {
        let (start_ms, end_ms) = subtitle_milliseconds(line, fps);
        let style = roles
            .get(&line.character_name)
            .map(|(_, style)| style.as_str())
            .unwrap_or("Default");
        writeln!(
            document,
            "Dialogue: 0,{},{},{},{},0,0,0,,{}",
            ass_timestamp(start_ms),
            ass_timestamp(end_ms),
            style,
            ass_header_field(&line.character_name),
            ass_text(&line.text)
        )
        .expect("String writes cannot fail");
    }
    Ok(document.replace('\n', "\r\n"))
}

pub fn export_ass(
    project: &Project,
    fps: f64,
    output: &Path,
    language_name: &str,
) -> Result<(), String> {
    write_text(output, &ass_document(project, fps, language_name)?)
}

/// Build the XML dialect understood by Coquerythmo's Cappella DETX importer.
/// Role, loop and shot metadata are retained; unsupported markers are omitted.
pub fn detx_document(project: &Project, fps: f64, language_name: &str) -> Result<String, String> {
    validate_fps(fps)?;
    let lines = delivery_lines(project);
    let mut roles = BTreeMap::<String, ([f32; 4], String)>::new();
    for line in &lines {
        let next_index = roles.len() + 1;
        roles
            .entry(line.character_name.clone())
            .or_insert_with(|| (line.character_color, format!("role_{next_index}")));
    }
    for character in project.known_characters() {
        let next_index = roles.len() + 1;
        roles
            .entry(character.name.clone())
            .or_insert_with(|| (character.color, format!("role_{next_index}")));
    }

    let mut document =
        String::from("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<detx>\n  <header>\n");
    writeln!(
        document,
        "    <language name=\"{}\" />",
        xml_escape(language_name.trim())
    )
    .expect("String writes cannot fail");
    writeln!(document, "    <framerate value=\"{fps}\" />").expect("String writes cannot fail");
    document.push_str("  </header>\n  <roles>\n");
    for (name, (color, id)) in &roles {
        writeln!(
            document,
            "    <role id=\"{}\" name=\"{}\" color=\"{}\" />",
            xml_escape(id),
            xml_escape(name),
            rgb_hex(*color)
        )
        .expect("String writes cannot fail");
    }
    document.push_str("  </roles>\n  <body>\n");

    let mut markers: Vec<_> = project
        .markers()
        .iter()
        .filter(|marker| matches!(marker.kind, MarkerKind::Boucle | MarkerKind::SceneChange))
        .collect();
    markers.sort_by_key(|marker| marker.frame);
    for marker in markers {
        let tag = if marker.kind == MarkerKind::Boucle {
            "loop"
        } else {
            "shot"
        };
        writeln!(
            document,
            "    <{tag} timecode=\"{}\" />",
            frame_timecode(marker.frame, fps)
        )
        .expect("String writes cannot fail");
    }

    for line in lines {
        let role = roles
            .get(&line.character_name)
            .map(|(_, id)| id.as_str())
            .unwrap_or("role_1");
        let track = nearest_detx_track(line.y_slot);
        let voice = if is_voice_off(&line.note) {
            " voice=\"off\""
        } else {
            ""
        };
        writeln!(
            document,
            "    <line role=\"{}\" track=\"{}\"{}>",
            xml_escape(role),
            track,
            voice
        )
        .expect("String writes cannot fail");
        writeln!(
            document,
            "      <lipsync timecode=\"{}\" type=\"in_open\" />",
            frame_timecode(line.start_frame, fps)
        )
        .expect("String writes cannot fail");
        writeln!(
            document,
            "      <text>{}</text>",
            xml_escape(&single_line_text(&line.text))
        )
        .expect("String writes cannot fail");
        writeln!(
            document,
            "      <lipsync timecode=\"{}\" type=\"out_open\" />",
            frame_timecode(line.end_frame(), fps)
        )
        .expect("String writes cannot fail");
        document.push_str("    </line>\n");
    }
    document.push_str("  </body>\n</detx>\n");
    Ok(document)
}

pub fn export_detx(
    project: &Project,
    fps: f64,
    output: &Path,
    language_name: &str,
) -> Result<(), String> {
    write_text(output, &detx_document(project, fps, language_name)?)
}

/// Build an RFC 4180-compatible cross-reference CSV. The UTF-8 BOM makes the
/// result open reliably in common spreadsheet applications.
pub fn cross_reference_csv_document(
    project: &Project,
    fps: f64,
    language_name: &str,
) -> Result<String, String> {
    validate_fps(fps)?;
    let loop_starts = loop_starts(project);
    let mut csv =
        String::from("\u{feff}Language,Loop,In,Out,Duration,Character,Voice actors,Text,Note\r\n");
    for line in delivery_lines(project) {
        let fields = [
            language_name.to_string(),
            loop_number(line.start_frame, &loop_starts).to_string(),
            frame_timecode(line.start_frame, fps),
            frame_timecode(line.end_frame(), fps),
            frame_timecode(line.duration_frames, fps),
            line.character_name.clone(),
            line.voice_actor_names.join(" | "),
            normalized_text(&line.text),
            normalized_text(&line.note),
        ];
        csv.push_str(
            &fields
                .iter()
                .map(|field| csv_field(field))
                .collect::<Vec<_>>()
                .join(","),
        );
        csv.push_str("\r\n");
    }
    Ok(csv)
}

pub fn export_cross_reference_csv(
    project: &Project,
    fps: f64,
    output: &Path,
    language_name: &str,
) -> Result<(), String> {
    write_text(
        output,
        &cross_reference_csv_document(project, fps, language_name)?,
    )
}

fn validate_fps(fps: f64) -> Result<(), String> {
    if fps.is_finite() && fps > 0.0 {
        Ok(())
    } else {
        Err(format!("Invalid FPS for delivery export: {fps}"))
    }
}

fn write_text(output: &Path, text: &str) -> Result<(), String> {
    std::fs::write(output, text.as_bytes())
        .map_err(|error| format!("Cannot write {}: {error}", output.display()))
}

fn delivery_lines(project: &Project) -> Vec<&RythmoLine> {
    let mut lines: Vec<_> = project
        .lines()
        .filter(|line| {
            line.duration_frames > 0 && line.end_frame() > 0 && !line.text.trim().is_empty()
        })
        .collect();
    lines.sort_by_key(|line| (line.start_frame, line.end_frame(), line.id));
    lines
}

fn subtitle_milliseconds(line: &RythmoLine, fps: f64) -> (u64, u64) {
    let start = ((line.start_frame.max(0) as f64 / fps) * 1000.0).round() as u64;
    let mut end = ((line.end_frame().max(0) as f64 / fps) * 1000.0).round() as u64;
    if end <= start {
        end = start + 1;
    }
    (start, end)
}

fn srt_timestamp(milliseconds: u64) -> String {
    let hours = milliseconds / 3_600_000;
    let minutes = (milliseconds / 60_000) % 60;
    let seconds = (milliseconds / 1_000) % 60;
    let millis = milliseconds % 1_000;
    format!("{hours:02}:{minutes:02}:{seconds:02},{millis:03}")
}

fn ass_timestamp(milliseconds: u64) -> String {
    let centiseconds = (milliseconds + 5) / 10;
    let hours = centiseconds / 360_000;
    let minutes = (centiseconds / 6_000) % 60;
    let seconds = (centiseconds / 100) % 60;
    let centis = centiseconds % 100;
    format!("{hours}:{minutes:02}:{seconds:02}.{centis:02}")
}

fn normalized_text(text: &str) -> String {
    text.trim().replace("\r\n", "\n").replace('\r', "\n")
}

fn single_line_text(text: &str) -> String {
    normalized_text(text)
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty())
        .collect::<Vec<_>>()
        .join(" ")
}

fn ass_header_field(text: &str) -> String {
    single_line_text(text).replace(',', ";")
}

fn ass_text(text: &str) -> String {
    normalized_text(text)
        .replace('\\', "\\\\")
        .replace('{', "\\{")
        .replace('}', "\\}")
        .replace('\n', "\\N")
}

fn ass_color(color: [f32; 4]) -> String {
    let byte = |component: f32| (component.clamp(0.0, 1.0) * 255.0).round() as u8;
    let alpha = 255_u8.saturating_sub(byte(color[3]));
    format!(
        "&H{alpha:02X}{:02X}{:02X}{:02X}",
        byte(color[2]),
        byte(color[1]),
        byte(color[0])
    )
}

fn rgb_hex(color: [f32; 4]) -> String {
    let byte = |component: f32| (component.clamp(0.0, 1.0) * 255.0).round() as u8;
    format!(
        "#{:02X}{:02X}{:02X}",
        byte(color[0]),
        byte(color[1]),
        byte(color[2])
    )
}

fn xml_escape(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&apos;")
}

fn nearest_detx_track(y_slot: f32) -> usize {
    [0.25_f32, 0.5, 0.75, 1.0]
        .iter()
        .enumerate()
        .min_by(|(_, left), (_, right)| {
            (y_slot - **left).abs().total_cmp(&(y_slot - **right).abs())
        })
        .map(|(index, _)| index)
        .unwrap_or(1)
}

fn is_voice_off(note: &str) -> bool {
    let note = note.to_lowercase();
    note.contains("voix off") || note.contains("voice off")
}

fn frame_timecode(frame: i64, fps: f64) -> String {
    let nominal_fps = fps.round().max(1.0) as i64;
    let frame = frame.max(0);
    let hours = frame / (nominal_fps * 3600);
    let minutes = (frame / (nominal_fps * 60)) % 60;
    let seconds = (frame / nominal_fps) % 60;
    let frames = frame % nominal_fps;
    format!("{hours:02}:{minutes:02}:{seconds:02}:{frames:02}")
}

fn csv_field(field: &str) -> String {
    if field.contains([',', '"', '\r', '\n']) {
        format!("\"{}\"", field.replace('"', "\"\""))
    } else {
        field.to_string()
    }
}

fn loop_starts(project: &Project) -> Vec<i64> {
    let mut starts: Vec<_> = project
        .markers()
        .iter()
        .filter(|marker| marker.kind == MarkerKind::Boucle)
        .map(|marker| marker.frame.max(0))
        .collect();
    starts.sort_unstable();
    starts.dedup();
    if starts.is_empty() {
        // A project without explicit loop markers still has one useful
        // delivery interval. Do not synthesize an extra loop when markers do
        // exist: their numbering must remain faithful to the authored grid.
        starts.push(0);
    }
    starts
}

fn loop_number(frame: i64, starts: &[i64]) -> usize {
    starts
        .partition_point(|start| *start <= frame.max(0))
        .max(1)
}

