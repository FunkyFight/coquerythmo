/// Create a loops-by-characters presence grid as a minimal PDF. A role is
/// marked when any of its lines overlaps a loop interval.
pub fn presence_grid_pdf_bytes(
    project: &Project,
    fps: f64,
    language_name: &str,
) -> Result<Vec<u8>, String> {
    validate_fps(fps)?;
    let spans = loop_spans(project);
    let mut characters = BTreeSet::<String>::new();
    for character in project.known_characters() {
        if !character.name.trim().is_empty() {
            characters.insert(character.name.clone());
        }
    }
    for line in project.lines() {
        if !line.character_name.trim().is_empty() {
            characters.insert(line.character_name.clone());
        }
    }
    let characters: Vec<_> = characters.into_iter().collect();
    let lines: Vec<_> = project.lines().collect();

    const MAX_CHARACTER_COLUMNS: usize = 10;
    const MAX_LOOP_ROWS: usize = 22;
    let character_chunks: Vec<&[String]> = if characters.is_empty() {
        vec![&[]]
    } else {
        characters.chunks(MAX_CHARACTER_COLUMNS).collect()
    };
    let span_chunks: Vec<&[LoopSpan]> = if spans.is_empty() {
        vec![&[]]
    } else {
        spans.chunks(MAX_LOOP_ROWS).collect()
    };
    let mut pages = Vec::new();

    for (character_chunk_index, character_chunk) in character_chunks.iter().enumerate() {
        for span_chunk in &span_chunks {
            let mut page = PdfCanvas::default();
            page.text(
                PDF_MARGIN,
                PDF_HEIGHT - 29.0,
                16.0,
                true,
                "Loop presence grid",
            );
            page.text(
                PDF_MARGIN,
                PDF_HEIGHT - 47.0,
                8.5,
                false,
                &format!(
                    "Language: {}   Roles {}-{} of {}",
                    display_language(language_name),
                    character_chunk_index * MAX_CHARACTER_COLUMNS + 1,
                    (character_chunk_index * MAX_CHARACTER_COLUMNS + character_chunk.len()).max(1),
                    characters.len()
                ),
            );

            let first_width = 128.0;
            let roles_width = PDF_WIDTH - PDF_MARGIN * 2.0 - first_width;
            let role_width = if character_chunk.is_empty() {
                roles_width
            } else {
                roles_width / character_chunk.len() as f32
            };
            let header_top = 520.0;
            let header_height = 42.0;
            page.fill_rect(
                PDF_MARGIN,
                header_top - header_height,
                first_width,
                header_height,
                0.86,
            );
            page.stroke_rect(
                PDF_MARGIN,
                header_top - header_height,
                first_width,
                header_height,
            );
            page.text(
                PDF_MARGIN + 4.0,
                header_top - 24.0,
                7.5,
                true,
                "Loop / time range",
            );
            let mut x = PDF_MARGIN + first_width;
            for character in *character_chunk {
                page.fill_rect(
                    x,
                    header_top - header_height,
                    role_width,
                    header_height,
                    0.86,
                );
                page.stroke_rect(x, header_top - header_height, role_width, header_height);
                for (line_index, text) in wrap_pdf_text(character, role_width - 6.0, 6.5, 3)
                    .iter()
                    .enumerate()
                {
                    page.text(
                        x + 3.0,
                        header_top - 12.0 - line_index as f32 * 8.0,
                        6.5,
                        true,
                        text,
                    );
                }
                x += role_width;
            }

            let row_height = 19.0;
            let mut top = header_top - header_height;
            if span_chunk.is_empty() {
                page.text(PDF_MARGIN, top - 24.0, 9.0, false, "No loops to export.");
            }
            for span in *span_chunk {
                let bottom = top - row_height;
                if span.number % 2 == 0 {
                    page.fill_rect(
                        PDF_MARGIN,
                        bottom,
                        PDF_WIDTH - PDF_MARGIN * 2.0,
                        row_height,
                        0.97,
                    );
                }
                page.stroke_rect(PDF_MARGIN, bottom, first_width, row_height);
                page.text(
                    PDF_MARGIN + 4.0,
                    bottom + 6.0,
                    7.0,
                    true,
                    &format!(
                        "{}  {} - {}",
                        span.number,
                        frame_timecode(span.start, fps),
                        frame_timecode(span.end, fps)
                    ),
                );
                x = PDF_MARGIN + first_width;
                for character in *character_chunk {
                    page.stroke_rect(x, bottom, role_width, row_height);
                    let present = lines.iter().any(|line| {
                        line.character_name == *character
                            && line.duration_frames > 0
                            && line.start_frame < span.end
                            && line.end_frame() > span.start
                    });
                    if present {
                        page.text(x + role_width / 2.0 - 2.5, bottom + 5.5, 8.5, true, "X");
                    }
                    x += role_width;
                }
                top = bottom;
            }
            pages.push(page);
        }
    }

    add_pdf_footers(&mut pages);
    Ok(build_pdf(&pages))
}

