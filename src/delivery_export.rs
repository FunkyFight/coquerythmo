#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum AudioTrackKind {
    Original,
    Instrumental,
}

impl AudioTrackKind {
    pub fn label(self) -> &'static str {
        match self {
            Self::Original => "original",
            Self::Instrumental => "instrumental",
        }
    }
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum AudioDeliveryFormat {
    Mp3,
    Wav,
    Bwf,
}

impl AudioDeliveryFormat {
    pub fn extension(self) -> &'static str {
        match self {
            Self::Mp3 => "mp3",
            Self::Wav | Self::Bwf => "wav",
        }
    }
}

#[derive(Clone, Debug)]
pub struct AudioExportOptions<'a> {
    pub format: AudioDeliveryFormat,
    pub track: AudioTrackKind,
    pub language_name: &'a str,
    pub stem_name: &'a str,
    /// Optional delivery duration. When set, FFmpeg pads or trims the adjusted
    /// audio to exactly this number of project frames.
    pub duration_frames: Option<i64>,
}

impl<'a> AudioExportOptions<'a> {
    pub fn new(format: AudioDeliveryFormat, track: AudioTrackKind, language_name: &'a str) -> Self {
        Self {
            format,
            track,
            language_name,
            stem_name: track.label(),
            duration_frames: None,
        }
    }
}

#[derive(Clone, Debug)]
pub struct AudioStemExport<'a> {
    pub input: &'a Path,
    pub output: &'a Path,
    pub track: AudioTrackKind,
    pub language_name: &'a str,
    pub stem_name: &'a str,
    pub duration_frames: Option<i64>,
}

/// Transcode one source or instrumental track to MP3, WAV or BWF. The offset
/// is selected from the active project's settings according to `options.track`.
/// FFmpeg writes a sibling temporary file and only replaces `output` after a
/// successful transcode.
pub fn export_audio(
    project: &Project,
    fps: f64,
    input: &Path,
    output: &Path,
    options: &AudioExportOptions<'_>,
    cancel: &AtomicBool,
) -> Result<(), String> {
    validate_fps(fps)?;
    if cancel.load(Ordering::Relaxed) {
        return Err(DELIVERY_EXPORT_CANCELLED_MESSAGE.to_string());
    }
    if let Some(duration_frames) = options.duration_frames {
        if duration_frames <= 0 {
            return Err(format!(
                "Audio delivery duration must be positive (got {duration_frames} frames)"
            ));
        }
    }

    let offset_frames = match options.track {
        AudioTrackKind::Original => project.settings().source_audio_offset_frames,
        AudioTrackKind::Instrumental => project.settings().instrumental_audio_offset_frames,
    };
    let filter = audio_delivery_filter(offset_frames, fps, options.duration_frames);
    let temporary = temporary_audio_path(output, options.format);
    let _ = std::fs::remove_file(&temporary);

    let mut command = media_binary::command("ffmpeg");
    command
        .arg("-nostdin")
        .arg("-hide_banner")
        .arg("-i")
        .arg(input)
        .args(["-map", "0:a:0", "-vn", "-af", &filter, "-map_metadata", "0"]);

    let title = if options.stem_name.trim().is_empty() {
        options.track.label()
    } else {
        options.stem_name.trim()
    };
    command
        .arg("-metadata")
        .arg(format!("title={title}"))
        .arg("-metadata")
        .arg(format!("language={}", options.language_name.trim()));

    match options.format {
        AudioDeliveryFormat::Mp3 => {
            command.args([
                "-c:a",
                "libmp3lame",
                "-b:a",
                "320k",
                "-id3v2_version",
                "3",
                "-f",
                "mp3",
            ]);
        }
        AudioDeliveryFormat::Wav => {
            command.args(["-c:a", "pcm_s24le", "-ar", "48000", "-f", "wav"]);
        }
        AudioDeliveryFormat::Bwf => {
            let description = format!(
                "Coquerythmo stem: {title}; language: {}",
                display_language(options.language_name)
            );
            command
                .args([
                    "-c:a",
                    "pcm_s24le",
                    "-ar",
                    "48000",
                    "-write_bext",
                    "1",
                    "-rf64",
                    "auto",
                ])
                .arg("-metadata")
                .arg("originator=Coquerythmo")
                .arg("-metadata")
                .arg(format!("description={description}"))
                .arg("-metadata")
                .arg("coding_history=A=PCM,F=48000,W=24")
                .args(["-f", "wav"]);
        }
    }

    if let Some(duration_frames) = options.duration_frames {
        command
            .arg("-t")
            .arg(format_decimal(duration_frames as f64 / fps));
    }

    let mut child = command
        .args(["-nostats", "-v", "warning", "-y"])
        .arg(&temporary)
        .stdout(Stdio::null())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|error| format!("Cannot start FFmpeg audio export: {error}"))?;

    let stderr_thread = child.stderr.take().map(|mut stderr| {
        std::thread::spawn(move || {
            let mut details = String::new();
            let _ = stderr.read_to_string(&mut details);
            details
        })
    });

    let status = loop {
        if cancel.load(Ordering::Relaxed) {
            let _ = child.kill();
            let _ = child.wait();
            let _ = stderr_thread.and_then(|thread| thread.join().ok());
            let _ = std::fs::remove_file(&temporary);
            return Err(DELIVERY_EXPORT_CANCELLED_MESSAGE.to_string());
        }
        match child.try_wait() {
            Ok(Some(status)) => break status,
            Ok(None) => {}
            Err(error) => {
                let _ = child.kill();
                let _ = child.wait();
                let _ = stderr_thread.and_then(|thread| thread.join().ok());
                let _ = std::fs::remove_file(&temporary);
                return Err(format!("Cannot wait for FFmpeg audio export: {error}"));
            }
        }
        std::thread::sleep(Duration::from_millis(40));
    };
    let stderr = stderr_thread
        .and_then(|thread| thread.join().ok())
        .unwrap_or_default();

    if !status.success() {
        let _ = std::fs::remove_file(&temporary);
        let details = stderr.trim();
        return if details.is_empty() {
            Err("FFmpeg audio export failed".to_string())
        } else {
            Err(format!("FFmpeg audio export failed: {details}"))
        };
    }

    replace_output(&temporary, output)
}

