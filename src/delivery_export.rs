fn loop_spans(project: &Project) -> Vec<LoopSpan> {
    let starts = loop_starts(project);
    let content_end = project
        .lines()
        .map(RythmoLine::end_frame)
        .chain(project.markers().iter().map(|marker| marker.frame))
        .max()
        .unwrap_or(1)
        .max(1);
    starts
        .iter()
        .enumerate()
        .map(|(index, start)| {
            let next_loop = starts.get(index + 1).copied();
            let next_out = project
                .markers()
                .iter()
                .filter(|marker| marker.kind == MarkerKind::Out && marker.frame > *start)
                .map(|marker| marker.frame)
                .min();
            let end = next_loop
                .into_iter()
                .chain(next_out)
                .min()
                .unwrap_or(content_end)
                .max(*start + 1);
            LoopSpan {
                number: index + 1,
                start: *start,
                end,
            }
        })
        .collect()
}

