const PDF_WIDTH: f32 = 842.0;
const PDF_HEIGHT: f32 = 595.0;
const PDF_MARGIN: f32 = 24.0;
const PDF_UNICODE_RASTER_SCALE: f32 = 4.0;

struct PdfImageMask {
    width: u32,
    height: u32,
    packed_bits: Vec<u8>,
    display_width: f32,
    display_height: f32,
    baseline_from_bottom: f32,
}

#[derive(Default)]
struct PdfCanvas {
    content: String,
    image_masks: Vec<PdfImageMask>,
}

impl PdfCanvas {
    fn text(&mut self, x: f32, y: f32, size: f32, bold: bool, text: &str) {
        if !can_encode_win_ansi(text) {
            if let Some(image) = rasterize_pdf_text(text, size, bold) {
                let image_index = self.image_masks.len() + 1;
                let image_y = y - image.baseline_from_bottom;
                writeln!(
                    self.content,
                    "/Span << /ActualText <{}> >> BDC",
                    pdf_utf16_hex(text)
                )
                .expect("String writes cannot fail");
                writeln!(
                    self.content,
                    "q 0 g {:.2} 0 0 {:.2} {x:.2} {image_y:.2} cm /Im{image_index} Do Q",
                    image.display_width, image.display_height
                )
                .expect("String writes cannot fail");
                self.content.push_str("EMC\n");
                self.image_masks.push(image);
                return;
            }
            // Even when the host has no usable glyph for the requested script,
            // never silently turn the content into question marks. Draw a
            // conventional missing-glyph grid while retaining the exact text
            // in ActualText for copy/paste and accessibility.
            writeln!(
                self.content,
                "/Span << /ActualText <{}> >> BDC",
                pdf_utf16_hex(text)
            )
            .expect("String writes cannot fail");
            let glyph_width = (size * 0.65).max(2.0);
            for index in 0..text.chars().count().min(24) {
                let glyph_x = x + index as f32 * (glyph_width + 1.0);
                writeln!(
                    self.content,
                    "q 0.35 G 0.45 w {glyph_x:.2} {:.2} {glyph_width:.2} {size:.2} re S Q",
                    y - size * 0.22
                )
                .expect("String writes cannot fail");
            }
            self.content.push_str("EMC\n");
            return;
        }

        let font = if bold { "F2" } else { "F1" };
        writeln!(
            self.content,
            "BT /{font} {size:.2} Tf 0 g 1 0 0 1 {x:.2} {y:.2} Tm ({}) Tj ET",
            pdf_string(text)
        )
        .expect("String writes cannot fail");
    }

    fn fill_rect(&mut self, x: f32, y: f32, width: f32, height: f32, gray: f32) {
        writeln!(
            self.content,
            "q {:.3} g {x:.2} {y:.2} {width:.2} {height:.2} re f Q",
            gray.clamp(0.0, 1.0)
        )
        .expect("String writes cannot fail");
    }

    fn stroke_rect(&mut self, x: f32, y: f32, width: f32, height: f32) {
        writeln!(
            self.content,
            "q 0.72 G 0.45 w {x:.2} {y:.2} {width:.2} {height:.2} re S Q"
        )
        .expect("String writes cannot fail");
    }
}

fn rasterize_pdf_text(text: &str, size: f32, bold: bool) -> Option<PdfImageMask> {
    if text.is_empty() || !size.is_finite() || size <= 0.0 {
        return None;
    }

    let measured_width = crate::vector_text::measure_project_text_width_standalone(text, size)
        .unwrap_or_else(|| text.chars().count().max(1) as f32 * size);
    let raster_size = size * PDF_UNICODE_RASTER_SCALE;
    let width = ((measured_width + 4.0) * PDF_UNICODE_RASTER_SCALE)
        .ceil()
        .clamp(1.0, 16_384.0) as u32;
    let height = (raster_size * 1.4).ceil().clamp(1.0, 4_096.0) as u32;
    let rendered = crate::vector_text::render_project_text_natural_standalone(
        text,
        raster_size,
        width,
        height,
    )?;
    if rendered.pixels.len() != width as usize * height as usize * 4 {
        return None;
    }

    let mut coverage = vec![false; width as usize * height as usize];
    for (pixel_index, pixel) in rendered.pixels.chunks_exact(4).enumerate() {
        coverage[pixel_index] = pixel[3] >= 24;
    }
    if bold {
        let original = coverage.clone();
        for y in 0..height as usize {
            for x in 0..width as usize {
                if !original[y * width as usize + x] {
                    continue;
                }
                if x + 1 < width as usize {
                    coverage[y * width as usize + x + 1] = true;
                }
                if y + 1 < height as usize {
                    coverage[(y + 1) * width as usize + x] = true;
                }
            }
        }
    }
    if !coverage.iter().any(|covered| *covered) {
        log::warn!(
            "No renderable glyph found for PDF Unicode text ({} characters)",
            text.chars().count()
        );
        return None;
    }

    let row_bytes = width.div_ceil(8) as usize;
    let mut packed_bits = vec![0_u8; row_bytes * height as usize];
    for y in 0..height as usize {
        for x in 0..width as usize {
            if coverage[y * width as usize + x] {
                packed_bits[y * row_bytes + x / 8] |= 1 << (7 - x % 8);
            }
        }
    }

    let display_width = width as f32 / PDF_UNICODE_RASTER_SCALE;
    let display_height = height as f32 / PDF_UNICODE_RASTER_SCALE;
    Some(PdfImageMask {
        width,
        height,
        packed_bits,
        display_width,
        display_height,
        baseline_from_bottom: (display_height - size).max(0.0),
    })
}

#[derive(Debug)]
struct CrossReferenceRow {
    loop_number: String,
    start: String,
    end: String,
    duration: String,
    character: String,
    voice_actors: String,
    text: String,
    note: String,
}

/// Create a minimal, dependency-free PDF containing the dialogue cross
/// reference. The returned bytes can be embedded in an archive or written by a
/// caller without creating a temporary file.
pub fn cross_reference_pdf_bytes(
    project: &Project,
    fps: f64,
    language_name: &str,
) -> Result<Vec<u8>, String> {
    validate_fps(fps)?;
    let starts = loop_starts(project);
    let rows: Vec<_> = delivery_lines(project)
        .into_iter()
        .map(|line| CrossReferenceRow {
            loop_number: loop_number(line.start_frame, &starts).to_string(),
            start: frame_timecode(line.start_frame, fps),
            end: frame_timecode(line.end_frame(), fps),
            duration: frame_timecode(line.duration_frames, fps),
            character: line.character_name.clone(),
            voice_actors: line.voice_actor_names.join(", "),
            text: single_line_text(&line.text),
            note: single_line_text(&line.note),
        })
        .collect();

    let widths = [30.0, 58.0, 58.0, 55.0, 76.0, 88.0, 329.0, 100.0];
    let headers = [
        "Loop",
        "In",
        "Out",
        "Dur.",
        "Character",
        "Actors",
        "Text",
        "Note",
    ];
    let mut pages = Vec::<PdfCanvas>::new();
    let mut page = cross_reference_page(language_name, &headers, &widths);
    let mut y = 500.0;

    if rows.is_empty() {
        page.text(
            PDF_MARGIN,
            472.0,
            9.0,
            false,
            "No dialogue lines to export.",
        );
    }

    for row in rows {
        let cells = [
            row.loop_number,
            row.start,
            row.end,
            row.duration,
            row.character,
            row.voice_actors,
            row.text,
            row.note,
        ];
        let wrapped: Vec<Vec<String>> = cells
            .iter()
            .zip(widths)
            .map(|(cell, width)| wrap_pdf_text(cell, width - 6.0, 7.0, 5))
            .collect();
        let line_count = wrapped.iter().map(Vec::len).max().unwrap_or(1).max(1);
        let row_height = (line_count as f32 * 9.0 + 6.0).max(17.0);

        if y - row_height < 38.0 {
            pages.push(page);
            page = cross_reference_page(language_name, &headers, &widths);
            y = 500.0;
        }

        let bottom = y - row_height;
        let mut x = PDF_MARGIN;
        for (column, (cell_lines, width)) in wrapped.iter().zip(widths).enumerate() {
            if column == 0 {
                page.fill_rect(x, bottom, width, row_height, 0.965);
            }
            page.stroke_rect(x, bottom, width, row_height);
            for (line_index, text) in cell_lines.iter().enumerate() {
                page.text(
                    x + 3.0,
                    y - 10.0 - line_index as f32 * 9.0,
                    7.0,
                    column == 0,
                    text,
                );
            }
            x += width;
        }
        y = bottom;
    }
    pages.push(page);
    add_pdf_footers(&mut pages);
    Ok(build_pdf(&pages))
}

