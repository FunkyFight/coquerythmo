//! Non-interactive delivery exports for an active bande rythmo.
//!
//! This module deliberately contains no UI or video-rendering orchestration.  It
//! turns a [`Project`] into delivery documents and delegates audio transcoding
//! to FFmpeg.  Callers that manage several languages can invoke the same
//! functions once per language/project.

